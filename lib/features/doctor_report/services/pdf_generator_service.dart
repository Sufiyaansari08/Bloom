import 'dart:math' as math;
import 'dart:typed_data';
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'doctor_report_service.dart';

class PdfGeneratorService {
  static final primaryPurple = PdfColor.fromHex('#7051C7');
  static final primaryPink = PdfColor.fromHex('#F65E87');
  static final textDark = PdfColor.fromHex('#302A3A');
  static final textSecondary = PdfColor.fromHex('#8A8194');
  static final borderCol = PdfColor.fromHex('#E7DFEC');
  static final bgPink = PdfColor.fromHex('#FFF0F5');

  static String _cleanPdfText(String text) {
    return text
        .replaceAll('±', '+/- ')
        .replaceAll('–', '-')
        .replaceAll('—', '-')
        .replaceAll('’', "'")
        .replaceAll('‘', "'")
        .replaceAll('“', '"')
        .replaceAll('”', '"');
  }

  static Future<Uint8List> generateDoctorReport([
    DoctorReportData? data,
  ]) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(24),
        build: (pw.Context context) {
          return [
            _buildHeader(data),
            pw.SizedBox(height: 12),
            _buildPatientInfo(data),
            pw.SizedBox(height: 12),
            _buildReportOverview(data),
            pw.SizedBox(height: 12),
            pw.Row(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Expanded(child: _buildCycleSummaryChart(data)),
                pw.SizedBox(width: 16),
                pw.Expanded(child: _buildPeriodDetailsChart(data)),
              ],
            ),
            pw.SizedBox(height: 12),
            _buildSymptomsAndMoodTables(data),
            pw.SizedBox(height: 12),
            _buildLifestyleInsights(data),
            pw.SizedBox(height: 12),
            _buildObservations(data),
            pw.SizedBox(height: 16),
            pw.Center(
              child: pw.Text(
                'Generated by Bloom App on ${DateFormat('MMM d, yyyy').format(DateTime.now())}',
                style: pw.TextStyle(color: textSecondary, fontSize: 8),
              ),
            ),
          ];
        },
      ),
    );

    return pdf.save();
  }

  static pw.Widget _buildHeader([DoctorReportData? data]) {
    final rawDateRange =
        data?.dateRangeText ?? 'Feb 1 - Jul 31, 2026 (6 cycles)';
    final dateRange = _cleanPdfText(rawDateRange);

    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.symmetric(horizontal: 16, vertical: 12),
      decoration: pw.BoxDecoration(
        color: bgPink,
        border: pw.Border(left: pw.BorderSide(color: primaryPink, width: 4)),
      ),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text(
                'Bloom Medical Report',
                style: pw.TextStyle(
                  color: primaryPurple,
                  fontWeight: pw.FontWeight.bold,
                  fontSize: 16,
                ),
              ),
              pw.SizedBox(height: 2),
              pw.Text(
                'Confidential Patient Data',
                style: pw.TextStyle(color: primaryPink, fontSize: 10),
              ),
            ],
          ),
          pw.Text(
            'Date Range: $dateRange',
            style: pw.TextStyle(
              color: textDark,
              fontSize: 10,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
        ],
      ),
    );
  }

  static pw.Widget _buildPatientInfo([DoctorReportData? data]) {
    final name = _cleanPdfText(data?.userName ?? 'Guest');
    final age = _cleanPdfText(data?.userAge ?? '-');
    final dob = _cleanPdfText(data?.userDob ?? '-');
    final height = _cleanPdfText(data?.userHeight ?? '-');
    final weight = _cleanPdfText(data?.userWeight ?? '-');
    final bloodGroup = _cleanPdfText(data?.userBloodGroup ?? '-');

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        _buildSectionTitle('Patient Information'),
        pw.SizedBox(height: 8),
        pw.Container(
          width: double.infinity,
          padding: const pw.EdgeInsets.all(12),
          decoration: pw.BoxDecoration(border: pw.Border.all(color: borderCol)),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              _buildInfoCol('Name', name),
              _buildInfoCol('Age', age),
              _buildInfoCol('DOB', dob),
              _buildInfoCol('Height', height),
              _buildInfoCol('Weight', weight),
              _buildInfoCol('Blood Group', bloodGroup),
            ],
          ),
        ),
      ],
    );
  }

  static pw.Widget _buildReportOverview([DoctorReportData? data]) {
    final avgCycle = data != null ? '${data.avgCycleLength} days' : '29 days';
    final shortestCycle = data != null
        ? '${data.shortestCycle} days'
        : '28 days';
    final longestCycle = data != null ? '${data.longestCycle} days' : '31 days';
    final variation = data != null
        ? '+/- ${data.cycleVariationDays} days'
        : '+/- 2 days';

    final avgPeriod = data != null ? '${data.avgPeriodLength} days' : '5 days';
    final shortestPeriod = data != null
        ? '${data.shortestPeriod} days'
        : '4 days';
    final longestPeriod = data != null
        ? '${data.longestPeriod} days'
        : '6 days';
    final pain = _cleanPdfText(data?.painLabel ?? 'Moderate');

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        _buildSectionTitle('Key Metrics Overview'),
        pw.SizedBox(height: 8),
        pw.Row(
          children: [
            pw.Expanded(child: _buildMetricBox(avgCycle, 'Avg. Cycle')),
            pw.SizedBox(width: 8),
            pw.Expanded(
              child: _buildMetricBox(shortestCycle, 'Shortest Cycle'),
            ),
            pw.SizedBox(width: 8),
            pw.Expanded(child: _buildMetricBox(longestCycle, 'Longest Cycle')),
            pw.SizedBox(width: 8),
            pw.Expanded(child: _buildMetricBox(variation, 'Cycle Variation')),
          ],
        ),
        pw.SizedBox(height: 8),
        pw.Row(
          children: [
            pw.Expanded(child: _buildMetricBox(avgPeriod, 'Avg. Period')),
            pw.SizedBox(width: 8),
            pw.Expanded(
              child: _buildMetricBox(shortestPeriod, 'Shortest Period'),
            ),
            pw.SizedBox(width: 8),
            pw.Expanded(
              child: _buildMetricBox(longestPeriod, 'Longest Period'),
            ),
            pw.SizedBox(width: 8),
            pw.Expanded(child: _buildMetricBox(pain, 'Average Pain')),
          ],
        ),
      ],
    );
  }

  static pw.Widget _buildCycleSummaryChart([DoctorReportData? data]) {
    final points = (data != null && data.cycleBarPoints.isNotEmpty)
        ? data.cycleBarPoints
        : [
            const CycleChartPoint(index: 1, label: 'C1', length: 28),
            const CycleChartPoint(index: 2, label: 'C2', length: 30),
            const CycleChartPoint(index: 3, label: 'C3', length: 29),
            const CycleChartPoint(index: 4, label: 'C4', length: 31),
            const CycleChartPoint(index: 5, label: 'C5', length: 30),
            const CycleChartPoint(index: 6, label: 'C6', length: 29),
          ];

    // FixedAxis needs at least 2 distinct values on the axis to prevent division by zero in CartesianGrid
    final numBars = math.max(2, points.length);
    final xValues = List.generate(numBars, (i) => (i + 1).toDouble());

    final maxLen = points.map((p) => p.length).reduce(math.max);
    final yMax = (maxLen > 35 ? maxLen + 5 : 35).toDouble();
    final yInterval = (yMax / 5).ceilToDouble();
    final ySteps = List.generate(6, (i) => i * yInterval);

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        _buildSectionTitle('Cycle Length History'),
        pw.SizedBox(height: 8),
        pw.Container(
          height: 120,
          padding: const pw.EdgeInsets.all(12),
          decoration: pw.BoxDecoration(border: pw.Border.all(color: borderCol)),
          child: pw.Chart(
            grid: pw.CartesianGrid(
              xAxis: pw.FixedAxis(
                xValues,
                format: (v) => 'C${v.toInt()}',
                textStyle: const pw.TextStyle(fontSize: 8),
              ),
              yAxis: pw.FixedAxis(
                ySteps,
                textStyle: const pw.TextStyle(fontSize: 8),
              ),
            ),
            datasets: [
              pw.BarDataSet(
                color: primaryPink,
                width: 16,
                data: points
                    .map(
                      (p) => pw.PointChartValue(
                        p.index.toDouble(),
                        p.length.toDouble(),
                      ),
                    )
                    .toList(),
              ),
            ],
          ),
        ),
      ],
    );
  }

  static pw.Widget _buildPeriodDetailsChart([DoctorReportData? data]) {
    final points = (data != null && data.periodBarPoints.isNotEmpty)
        ? data.periodBarPoints
        : [
            const CycleChartPoint(index: 1, label: 'C1', length: 4),
            const CycleChartPoint(index: 2, label: 'C2', length: 5),
            const CycleChartPoint(index: 3, label: 'C3', length: 5),
            const CycleChartPoint(index: 4, label: 'C4', length: 6),
            const CycleChartPoint(index: 5, label: 'C5', length: 4),
            const CycleChartPoint(index: 6, label: 'C6', length: 5),
          ];

    // FixedAxis needs at least 2 distinct values on the axis to prevent division by zero in CartesianGrid
    final numBars = math.max(2, points.length);
    final xValues = List.generate(numBars, (i) => (i + 1).toDouble());

    final maxPeriod = points.map((p) => p.length).reduce(math.max);
    final yMax = (maxPeriod > 10 ? maxPeriod + 2 : 10).toDouble();
    final yInterval = (yMax / 5).ceilToDouble();
    final ySteps = List.generate(6, (i) => i * yInterval);

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        _buildSectionTitle('Period Length History'),
        pw.SizedBox(height: 8),
        pw.Container(
          height: 120,
          padding: const pw.EdgeInsets.all(12),
          decoration: pw.BoxDecoration(border: pw.Border.all(color: borderCol)),
          child: pw.Chart(
            grid: pw.CartesianGrid(
              xAxis: pw.FixedAxis(
                xValues,
                format: (v) => 'C${v.toInt()}',
                textStyle: const pw.TextStyle(fontSize: 8),
              ),
              yAxis: pw.FixedAxis(
                ySteps,
                textStyle: const pw.TextStyle(fontSize: 8),
              ),
            ),
            datasets: [
              pw.BarDataSet(
                color: primaryPurple,
                width: 16,
                data: points
                    .map(
                      (p) => pw.PointChartValue(
                        p.index.toDouble(),
                        p.length.toDouble(),
                      ),
                    )
                    .toList(),
              ),
            ],
          ),
        ),
      ],
    );
  }

  static pw.Widget _buildSymptomsAndMoodTables([DoctorReportData? data]) {
    final symptomRows = <pw.TableRow>[
      _buildTableHeader(['Symptom', 'Common Phase', 'Details']),
    ];
    if (data != null && data.symptomPatterns.isNotEmpty) {
      for (final s in data.symptomPatterns) {
        symptomRows.add(
          _buildTableRow([
            _cleanPdfText(s.name),
            _cleanPdfText(s.phase),
            _cleanPdfText(s.subtitle),
          ]),
        );
      }
    } else if (data != null && data.symptomPatterns.isEmpty) {
      symptomRows.add(
        _buildTableRow(['No symptoms logged', 'N/A', 'None recorded']),
      );
    } else {
      symptomRows.addAll([
        _buildTableRow(['Headache', 'Before period', '1-2 days before']),
        _buildTableRow(['Bloating', 'Before period', '2-4 days before']),
        _buildTableRow(['Cramps', 'During period', 'First 1-2 days']),
        _buildTableRow(['Mood Swings', 'During period', 'First 2 days']),
      ]);
    }

    final moodRows = <pw.TableRow>[
      _buildTableHeader(['Mood', 'Common Phase', 'Details']),
    ];
    if (data != null && data.moodTrends.isNotEmpty) {
      for (final m in data.moodTrends) {
        moodRows.add(
          _buildTableRow([
            _cleanPdfText(m.mood),
            _cleanPdfText(m.phase),
            _cleanPdfText(m.subtitle),
          ]),
        );
      }
    } else if (data != null && data.moodTrends.isEmpty) {
      moodRows.add(_buildTableRow(['No mood logs', 'N/A', 'None recorded']));
    } else {
      moodRows.addAll([
        _buildTableRow(['Not Great', 'Before period', '3-5 days before']),
        _buildTableRow(['Bad', 'During period', 'First 1-2 days']),
        _buildTableRow(['Great', 'After period', '2-5 days after']),
      ]);
    }

    return pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Expanded(
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              _buildSectionTitle('Symptom Patterns'),
              pw.SizedBox(height: 8),
              pw.Table(
                border: pw.TableBorder.all(color: borderCol),
                children: symptomRows,
              ),
            ],
          ),
        ),
        pw.SizedBox(width: 16),
        pw.Expanded(
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              _buildSectionTitle('Mood Trends'),
              pw.SizedBox(height: 8),
              pw.Table(
                border: pw.TableBorder.all(color: borderCol),
                children: moodRows,
              ),
            ],
          ),
        ),
      ],
    );
  }

  static pw.Widget _buildLifestyleInsights([DoctorReportData? data]) {
    final sleep = _cleanPdfText(data?.sleepFormatted ?? '6.5 hrs/night');
    final water = _cleanPdfText(data?.waterFormatted ?? '1.5 L/day');
    final activity = _cleanPdfText(data?.activityFormatted ?? 'Moderate');
    final stress = _cleanPdfText(data?.stressFormatted ?? 'High');

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        _buildSectionTitle('Lifestyle Averages'),
        pw.SizedBox(height: 8),
        pw.Container(
          width: double.infinity,
          padding: const pw.EdgeInsets.all(12),
          decoration: pw.BoxDecoration(border: pw.Border.all(color: borderCol)),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              _buildInfoCol('Sleep Average', sleep),
              _buildInfoCol('Water Intake', water),
              _buildInfoCol('Activity Level', activity),
              _buildInfoCol('Reported Stress', stress),
            ],
          ),
        ),
      ],
    );
  }

  static pw.Widget _buildObservations([DoctorReportData? data]) {
    final rawObservations =
        (data != null && data.observationsSummary.isNotEmpty)
        ? data.observationsSummary
        : 'Based on the logged data over 6 cycles, the patient\'s cycle is fairly regular with an average length of 29 days (variation +/- 2 days). '
              'The patient experiences moderate pain and mood swings primarily during the first few days of menstruation. '
              'High stress levels have been noted recently, correlating with a lower sleep average (6.5 hrs), which may affect overall energy and symptom severity.';

    final observations = _cleanPdfText(rawObservations);

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        _buildSectionTitle('Clinical Observations Summary'),
        pw.SizedBox(height: 8),
        pw.Container(
          width: double.infinity,
          padding: const pw.EdgeInsets.all(12),
          decoration: pw.BoxDecoration(
            color: PdfColor.fromHex('#FAFAFA'),
            border: pw.Border.all(color: borderCol),
          ),
          child: pw.Text(
            observations,
            style: pw.TextStyle(
              color: textDark,
              fontSize: 10,
              lineSpacing: 1.5,
            ),
          ),
        ),
      ],
    );
  }

  // --- Helpers ---

  static pw.Widget _buildSectionTitle(String title) {
    return pw.Text(
      title,
      style: pw.TextStyle(
        color: primaryPurple,
        fontWeight: pw.FontWeight.bold,
        fontSize: 12,
      ),
    );
  }

  static pw.Widget _buildInfoCol(String label, String value) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(label, style: pw.TextStyle(color: textSecondary, fontSize: 8)),
        pw.SizedBox(height: 2),
        pw.Text(
          value,
          style: pw.TextStyle(
            color: textDark,
            fontWeight: pw.FontWeight.bold,
            fontSize: 10,
          ),
        ),
      ],
    );
  }

  static pw.Widget _buildMetricBox(String value, String label) {
    return pw.Container(
      padding: const pw.EdgeInsets.symmetric(horizontal: 12, vertical: 8),
      decoration: pw.BoxDecoration(
        color: PdfColor.fromHex('#F5F5F5'),
        border: pw.Border.all(color: borderCol),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            value,
            style: pw.TextStyle(
              color: textDark,
              fontWeight: pw.FontWeight.bold,
              fontSize: 12,
            ),
          ),
          pw.SizedBox(height: 2),
          pw.Text(
            label,
            style: pw.TextStyle(color: textSecondary, fontSize: 8),
          ),
        ],
      ),
    );
  }

  static pw.TableRow _buildTableHeader(List<String> cells) {
    return pw.TableRow(
      decoration: pw.BoxDecoration(color: PdfColor.fromHex('#F5F5F5')),
      children: cells.map((cell) {
        return pw.Padding(
          padding: const pw.EdgeInsets.all(6),
          child: pw.Text(
            cell,
            style: pw.TextStyle(
              fontWeight: pw.FontWeight.bold,
              fontSize: 8,
              color: textDark,
            ),
          ),
        );
      }).toList(),
    );
  }

  static pw.TableRow _buildTableRow(List<String> cells) {
    return pw.TableRow(
      children: cells.map((cell) {
        return pw.Padding(
          padding: const pw.EdgeInsets.all(6),
          child: pw.Text(
            cell,
            style: pw.TextStyle(fontSize: 8, color: textDark),
          ),
        );
      }).toList(),
    );
  }
}
